"""ZeroScript 4.0 - Game Engine Update (Nodes, Auto-Fix, Webhooks)"""
import json
import urllib.error
import urllib.request

#: How long a Discord webhook call may take before the request is abandoned.
#: Without a timeout a slow (or hanging) Discord endpoint keeps a server
#: thread blocked forever - the dashboard would simply stop answering.
WEBHOOK_TIMEOUT = 10


def _node_data(node):
    """The `data` bag of a graph node, always as a dict."""
    data = node.get("data")
    return data if isinstance(data, dict) else {}


def node_to_luau(graph):
    """Converts a visual node graph JSON into executable Luau.

    The graph arrives straight from the browser, so every field is treated
    as untrusted: a node without a type, an edge that points at a node id
    that does not exist, or a non-object entry must not turn into a server
    error.  Anything that cannot be understood is skipped instead.
    """
    graph = graph if isinstance(graph, dict) else {}
    nodes = [n for n in (graph.get("nodes") or []) if isinstance(n, dict)]
    edges = [e for e in (graph.get("edges") or []) if isinstance(e, dict)]
    by_id = {n.get("id"): n for n in nodes if n.get("id") is not None}

    code = "--!strict\n-- Generated by ZeroScript Visual Blueprints\n\n"
    code += "local Players = game:GetService('Players')\n"
    code += "local Workspace = game:GetService('Workspace')\n\n"
    code += "local function main()\n"

    for node in nodes:
        if node.get("type") != "Event":
            continue
        event_val = _node_data(node).get("value", "")
        code += f"\t-- Event: {event_val}\n"
        for edge in edges:
            if edge.get("source") != node.get("id"):
                continue
            target = by_id.get(edge.get("target"))
            if target is None or target.get("type") != "Action":
                # An edge to a node that is not in the graph (or to a node
                # that is not an action) has no meaning - skip it rather
                # than failing the whole compile.
                continue
            action_val = str(_node_data(target).get("value", ""))
            code += f"\t-- Action: {action_val}\n"
            if "Explode" in action_val:
                parts = [p.strip() for p in action_val.split(",")]
                target_name = parts[1] if len(parts) > 1 and parts[1] else "Part"
                code += f"\tWorkspace:FindFirstChild('{target_name}'):Destroy()\n"

    code += "end\n\nmain()\n"
    return code


def send_discord_webhook(url, message):
    if not url or not url.startswith("https://discord.com/api/webhooks/"):
        return False, "Invalid Discord Webhook URL"

    data = {"embeds": [{"title": "ZeroScript Build Log",
                        "description": str(message or ""), "color": 0x7c5cff}]}
    req = urllib.request.Request(
        url, data=json.dumps(data).encode('utf-8'),
        headers={'Content-Type': 'application/json', 'User-Agent': 'ZeroScript/4.0'}
    )
    try:
        with urllib.request.urlopen(req, timeout=WEBHOOK_TIMEOUT) as resp:
            status = getattr(resp, "status", None) or resp.getcode()
            if status and int(status) >= 400:
                return False, f"Discord returned HTTP {status}"
            return True, "Webhook sent!"
    except urllib.error.HTTPError as e:
        return False, f"Discord returned HTTP {e.code}"
    except Exception as e:
        return False, str(e)


def auto_fix_error(error_msg, script_code):
    """Apply the local repairs for the reported error.

    The error message is not decoration - it decides whether a repair is
    possible at all.  The local fixer only knows how to upgrade the
    deprecated wait/spawn/delay calls, so an error that names none of them
    is reported as "no automatic repair" instead of handing back the
    untouched script as if it had been fixed.
    """
    try:
        import zs_ai
        code = script_code or ""
        error = (error_msg or "").strip()
        if error and not _mentions_deprecated_call(error):
            return False, ("no automatic repair for this error - the local "
                           "fixer only upgrades deprecated wait/spawn/delay "
                           "calls")
        return True, zs_ai.local_fix(code)
    except Exception as e:
        return False, str(e)


def _mentions_deprecated_call(error):
    """True when the reported error names one of the deprecated task calls."""
    lowered = error.lower()
    return any(name in lowered for name in ("wait", "spawn", "delay"))


def handle_post(handler, path, body):
    if path == "/api2/v4/node_graph":
        code = node_to_luau(body)
        return handler._send_json(200, {"ok": True, "code": code}), True

    if path == "/api2/v4/discord":
        ok, res = send_discord_webhook(body.get("url"), body.get("message"))
        return handler._send_json(200 if ok else 400, {"ok": ok, "msg": res}), True

    if path == "/api2/v4/auto_fix":
        ok, res = auto_fix_error(body.get("error"), body.get("code"))
        return handler._send_json(200 if ok else 400,
                                  {"ok": ok, "fixed_code": res, "msg": res}), True

    return None, False


